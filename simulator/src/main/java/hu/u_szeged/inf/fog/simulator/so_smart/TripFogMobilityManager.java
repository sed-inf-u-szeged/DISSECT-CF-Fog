package hu.u_szeged.inf.fog.simulator.so_smart;

import hu.mta.sztaki.lpds.cloud.simulator.DeferredEvent;
import hu.mta.sztaki.lpds.cloud.simulator.Timed;
import hu.u_szeged.inf.fog.simulator.iot.Device;
import hu.u_szeged.inf.fog.simulator.iot.mobility.GeoLocation;
import hu.u_szeged.inf.fog.simulator.iot.mobility.MobilityEvent;
import hu.u_szeged.inf.fog.simulator.iot.mobility.NomadicMobilityStrategy;
import hu.u_szeged.inf.fog.simulator.node.ComputingAppliance;
import hu.u_szeged.inf.fog.simulator.util.SimLogger;

import java.util.*;

/**
 * Manages traveler mobility and logical handovers between Fog nodes.
 * <p>
 * Trip execution remains controlled by TripSimulator.
 */
public class TripFogMobilityManager {

    private final Map<String, Trip> tripPlans = new HashMap<>();
    private final Map<String, MobileTraveler> travelers = new HashMap<>();

    private final List<ComputingAppliance> fogNodes;
    private final long movementIntervalMs;

    private final List<HandoverRecord> completedHandovers = new ArrayList<>();

    private int totalHandovers;

    /**
     * Creates a mobility manager for the given trips and Fog nodes.
     *
     * @param trips              planned trips
     * @param fogNodes           available Fog nodes
     * @param movementIntervalMs interval between position updates
     */
    public TripFogMobilityManager(
            List<Trip> trips,
            List<ComputingAppliance> fogNodes,
            long movementIntervalMs) {

        Objects.requireNonNull(trips, "Trips are required.");
        Objects.requireNonNull(fogNodes, "Fog nodes are required.");

        if (fogNodes.isEmpty()) {
            throw new IllegalArgumentException(
                    "At least one Fog node is required.");
        }

        if (movementIntervalMs <= 0) {
            throw new IllegalArgumentException(
                    "Movement interval must be positive.");
        }

        this.fogNodes = List.copyOf(fogNodes);
        this.movementIntervalMs = movementIntervalMs;

        for (ComputingAppliance node : this.fogNodes) {
            Objects.requireNonNull(node, "Fog node cannot be null.");
        }

        for (Trip trip : trips) {
            Objects.requireNonNull(trip, "Trip cannot be null.");

            if (tripPlans.putIfAbsent(trip.getId(), trip) != null) {
                throw new IllegalArgumentException(
                        "Duplicate trip ID: " + trip.getId());
            }
        }
    }

    /**
     * Reacts to trip lifecycle events.
     *
     * @param event the event generated by TripSimulator
     */
    public void onTripEvent(TripEvent event) {
        Objects.requireNonNull(event, "Trip event is required.");

        Trip trip = tripPlans.get(event.getTripId());

        if (trip == null) {
            throw new IllegalArgumentException(
                    "Unknown trip: " + event.getTripId());
        }

        switch (event.getType()) {
            case TRIP_STARTED:
                if (travelers.containsKey(trip.getId())) {
                    throw new IllegalStateException(
                            "Traveler already started: " + trip.getId());
                }

                MobileTraveler traveler = new MobileTraveler(trip);
                travelers.put(trip.getId(), traveler);

                SimLogger.logRun("FOG_ASSIGNED " + trip.getId()
                        + " -> " + traveler.servingFog.name);

                traveler.startMovement();
                break;

            case TRIP_COMPLETED:
            case TRIP_INTERRUPTED:
                MobileTraveler current = travelers.get(trip.getId());

                if (current != null) {
                    current.stopMovement();
                }
                break;

            default:
                // Segment completion does not change mobility scheduling.
                break;
        }
    }

    /**
     * Finds the geographically closest Fog node.
     *
     * @param position current traveler position
     * @return nearest Fog node
     */
    private ComputingAppliance findNearestFog(GeoLocation position) {
        ComputingAppliance nearest = null;
        double minimumDistance = Double.POSITIVE_INFINITY;

        for (ComputingAppliance fog : fogNodes) {
            double distance = position.calculateDistance(fog.geoLocation);

            if (distance < minimumDistance) {
                minimumDistance = distance;
                nearest = fog;
            }
        }

        return nearest;
    }

    /**
     * Represents one moving traveler.
     */
    private class MobileTraveler extends Device {

        private final Trip trip;

        private ComputingAppliance servingFog;
        private DeferredEvent handoverEvent;

        private boolean active = true;
        private boolean handoverPending;

        private int handovers;

        MobileTraveler(Trip trip) {
            this.trip = trip;
            this.freq = movementIntervalMs;

            GeoLocation origin = trip.getOrigin();

            this.geoLocation = new GeoLocation(
                    origin.latitude,
                    origin.longitude
            );

            this.servingFog = findNearestFog(geoLocation);

            // Model constant-speed movement over the entire trip.
            // Individual segment durations do not affect movement speed.
            double distanceMeters =
                    origin.calculateDistance(trip.getDestination());

            double speedMetersPerMs =
                    distanceMeters / trip.getTotalDurationMs();

            this.mobilityStrategy = new NomadicMobilityStrategy(
                    origin,
                    speedMetersPerMs,
                    trip.getDestination()
            );
        }

        /**
         * Starts periodic traveler position updates.
         */
        private void startMovement() {
            subscribe(movementIntervalMs);
        }

        /**
         * Updates the position and checks whether handover is needed.
         *
         * @param fires current simulation tick
         */
        @Override
        public void tick(long fires) {
            if (!active) {
                return;
            }

            MobilityEvent.changePositionEvent(
                    this,
                    mobilityStrategy.move(this)
            );

            ComputingAppliance nearest = findNearestFog(geoLocation);

            if (nearest != servingFog && !handoverPending) {
                startHandover(nearest);
            }
        }

        /**
         * Starts a logical Fog handover.
         *
         * @param targetFog the new Fog node
         */
        private void startHandover(ComputingAppliance targetFog) {
            ComputingAppliance previousFog = servingFog;

            Integer latency = previousFog.iaas.repositories.get(0)
                    .getLatencies()
                    .get(targetFog.iaas.repositories.get(0).getName());

            if (latency == null || latency < 0) {
                throw new IllegalStateException(
                        "Missing Fog connection: "
                                + previousFog.name + " -> "
                                + targetFog.name);
            }

            handoverPending = true;

            SimLogger.logRun("HANDOVER_STARTED "
                    + trip.getId()
                    + " | " + previousFog.name
                    + " -> " + targetFog.name);

            handoverEvent = new DeferredEvent(latency) {
                @Override
                protected void eventAction() {
                    if (!active) {
                        return;
                    }

                    servingFog = targetFog;
                    handovers++;
                    totalHandovers++;

                    completedHandovers.add(new HandoverRecord(
                            trip.getId(),
                            previousFog.name,
                            targetFog.name,
                            Timed.getFireCount(),
                            MobileTraveler.this.geoLocation
                    ));

                    handoverPending = false;
                    handoverEvent = null;

                    SimLogger.logRun("HANDOVER_COMPLETED "
                            + trip.getId()
                            + " | " + targetFog.name);
                }
            };
        }

        /**
         * Stops movement and cancels any unfinished handover.
         */
        private void stopMovement() {
            active = false;

            if (isSubscribed()) {
                unsubscribe();
            }

            if (handoverEvent != null) {
                handoverEvent.cancel();
                handoverEvent = null;
            }

            handoverPending = false;
        }
    }

    /**
     * Returns the currently assigned Fog node of a traveler.
     *
     * @param tripId trip identifier
     * @return assigned Fog node, or null if not started
     */
    public ComputingAppliance getServingFog(String tripId) {
        MobileTraveler traveler = travelers.get(tripId);
        return traveler == null ? null : traveler.servingFog;
    }

    /**
     * Returns the current geographical position of a traveler.
     *
     * @param tripId the trip identifier
     * @return current position, or null if the trip has not started
     */
    public GeoLocation getTravelerPosition(String tripId) {
        MobileTraveler traveler = travelers.get(tripId);

        if (traveler == null) {
            return null;
        }

        return new GeoLocation(
                traveler.geoLocation.latitude,
                traveler.geoLocation.longitude
        );
    }

    /**
     * Returns the completed handover count for a trip.
     *
     * @param tripId trip identifier
     * @return completed handovers
     */
    public int getHandoverCount(String tripId) {
        MobileTraveler traveler = travelers.get(tripId);
        return traveler == null ? 0 : traveler.handovers;
    }

    /**
     * Returns the total number of completed handovers.
     *
     * @return total handover count
     */
    public int getTotalHandovers() {
        return totalHandovers;
    }

    public List<HandoverRecord> getCompletedHandovers() {
        return List.copyOf(completedHandovers);
    }
}
